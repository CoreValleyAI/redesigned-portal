/**
 * Springs, defined once and shared by CSS, GSAP and the WebGL scenes.
 *
 * A spring is described the way Apple describes them: a perceptual
 * `duration` (how long it takes to look settled) and a `bounce` (0 = no
 * overshoot). From those come the physical constants
 *
 *   ω₀ = 2π / duration          (natural frequency)
 *   ζ  = 1 − bounce             (damping ratio; 1 = critically damped)
 *
 * and the step response x(t) from 0 to 1. With bounce 0 the curve has the
 * same shape for every duration, so the CSS `linear()` easing is one string
 * and only the animation duration changes per token.
 *
 * The CSS strings in app/styles/tokens.css are generated by `cssLinear()`;
 * after changing a spring, run scripts/print-springs.mjs and paste.
 */

export interface SpringSpec {
  /** Seconds until the motion looks settled. */
  duration: number;
  /** 0 = critically damped; 0.1–0.3 = a little overshoot. */
  bounce: number;
}

export const SPRINGS = {
  snappy: { duration: 0.3, bounce: 0 },
  smooth: { duration: 0.45, bounce: 0 },
  gentle: { duration: 0.7, bounce: 0 },
  /** After a flick or drag release only (slices, the dataset token). */
  throw: { duration: 0.4, bounce: 0.18 },
} as const satisfies Record<string, SpringSpec>;

/** Step response of the spring at time t (seconds), from 0 toward 1. */
export function springAt(spec: SpringSpec, t: number): number {
  if (t <= 0) return 0;
  const w0 = (2 * Math.PI) / spec.duration;
  const zeta = 1 - spec.bounce;
  if (zeta >= 1) {
    return 1 - (1 + w0 * t) * Math.exp(-w0 * t);
  }
  const wd = w0 * Math.sqrt(1 - zeta * zeta);
  const decay = Math.exp(-zeta * w0 * t);
  return 1 - decay * (Math.cos(wd * t) + ((zeta * w0) / wd) * Math.sin(wd * t));
}

/**
 * The spring as a CSS `linear()` easing over its own duration. Points are
 * placed where the curve bends most (dense early, sparse in the tail) and
 * the last value is pinned to 1 so the animation lands exactly.
 */
export function cssLinear(spec: SpringSpec, points = 14): string {
  const end = springAt(spec, spec.duration);
  const stops: string[] = ["0"];
  for (let i = 1; i < points; i++) {
    // Quadratic spacing: more stops where the curve moves fastest.
    const p = (i / points) ** 1.6;
    const v = springAt(spec, p * spec.duration) / end;
    stops.push(`${round(v)} ${round(p * 100, 1)}%`);
  }
  stops.push("1");
  return `linear(${stops.join(", ")})`;
}

function round(v: number, digits = 4) {
  const f = 10 ** digits;
  return String(Math.round(v * f) / f);
}

/**
 * A spring you can drive frame by frame and redirect mid-flight: it keeps
 * its velocity when the target changes, which is what makes interrupted
 * motion feel continuous (06 §0, "springs and interruption").
 */
export class Spring {
  value: number;
  target: number;
  velocity = 0;
  private w0: number;
  private zeta: number;

  constructor(initial: number, spec: SpringSpec = SPRINGS.smooth) {
    this.value = initial;
    this.target = initial;
    this.w0 = (2 * Math.PI) / spec.duration;
    this.zeta = 1 - spec.bounce;
  }

  set(spec: SpringSpec) {
    this.w0 = (2 * Math.PI) / spec.duration;
    this.zeta = 1 - spec.bounce;
  }

  /** Advance by dt seconds (semi-implicit Euler, sub-stepped for stability). */
  step(dt: number): number {
    const steps = Math.max(1, Math.ceil(dt / (1 / 240)));
    const h = dt / steps;
    const k = this.w0 * this.w0;
    const c = 2 * this.zeta * this.w0;
    for (let i = 0; i < steps; i++) {
      const a = -k * (this.value - this.target) - c * this.velocity;
      this.velocity += a * h;
      this.value += this.velocity * h;
    }
    return this.value;
  }

  get settled(): boolean {
    return Math.abs(this.value - this.target) < 1e-4 && Math.abs(this.velocity) < 1e-4;
  }

  snap(v: number) {
    this.value = v;
    this.target = v;
    this.velocity = 0;
  }
}

/**
 * Frame-rate independent exponential smoothing toward a target: the
 * "damped read" used for scroll progress and pointer positions. `halfLife`
 * is the time (s) it takes to close half the remaining distance.
 */
export function damp(current: number, target: number, halfLife: number, dt: number): number {
  if (halfLife <= 0) return target;
  return target + (current - target) * Math.pow(2, -dt / halfLife);
}
